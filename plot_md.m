% Paper figure selection and export. No experiments are run.
%
% Entry script for saved paper figures. The Gaussian comparison keeps a
% separate matching IID baseline for MWG and joint RWM. No simulation is run.

%% Resolve repository paths
driver=mfilename('fullpath');root=fileparts(driver);
addpath(genpath(fullfile(root,'src')));

%% Select datasets and saved results
selection='bayesian'; % 'gaussian': 2-by-3 MWG (top) / joint Hilbert (bottom)
                     % 'bayesian': Ripley/Pima; 'ripley' or 'pima': one dataset
                     % 'all': Bayesian and Gaussian figures
% Empty paths check runs/ newest to oldest for complete matching dimensions/N.
% Checkpoints and incomplete files are skipped; actual input paths are printed.
mwgMatFile='';
gaussianMatFile='';
ripleyMatFile='';
pimaMatFile='';
bayesianTest='projection'; % Paper figures use the standardized projection test
exponents=10:18;
saveFigures=true;   % true saves vector PDF and editable FIG
showFigures=true;

%% Render the selected figures and optional exports
paper=plot_paper_convergence(selection, ...
    'BayesianTest',bayesianTest, ...
    'NExponents',exponents, ...
    'MwgMatFile',mwgMatFile, ...
    'GaussianMatFile',gaussianMatFile, ...
    'RipleyMatFile',ripleyMatFile, ...
    'PimaMatFile',pimaMatFile, ...
    'SaveFigures',saveFigures, ...
    'ShowFigures',showFigures, ...
    'OutputDir',fullfile(root,'figures'), ...
    'LineWidth',1.8, ...
    'MarkerSize',6, ...
    'AxisFontSize',11, ...
    'LabelFontSize',16, ...
    'LegendFontSize',13, ...
    'TailCount',5);
