% Standard Gaussian fixed-horizon experiment. Edit all parameters here.
%
% Entry script for joint Gaussian RWM. Each transition proposes a whole-vector update.
% Statistics use projection only and one combined IID/Hilbert parfor per N.
% The runner returns raw replication estimates, summary tables and fitted slopes.
% T includes BurnIn; full defaults below are intended for the paper experiment.

%% Resolve repository paths
driver=mfilename('fullpath');
assert(~isempty(driver),'Add the experiment folder to the MATLAB path first');
root=fileparts(driver); addpath(genpath(fullfile(root,'src')));

%% Choose the initial particle distribution
% 'stationary': target-distributed initial particles.
% 'zero': every particle starts at the zero vector in every dimension.
% 'fixed' with InitialState=[]: every particle starts at the target mean mu.
initialization='zero';

%% Configure and run the joint-update experiment
results=run_gaussian_hilbert_experiment( ...
    'Target','standard', ... % mu=zeros(1,p), Sigma=eye(p) for each dimension
    'Dimensions',[2 4 8], ...
    'NExponents',10:18, ...
    'Replications',200, ...
    'T',128, ...
    'BurnIn',8, ...
    'HilbertBits',[], ... % Auto: min(20,floor(64/p)); explicit values are references
    'Seed',2026, ...
    'Mean',[], ...
    'Covariance',[], ...
    'StepScale',[], ...
    'Initialization',initialization, ...
    'InitialState',[], ...
    'SortCoordinates','marginal', ...
    'TailCount',5, ...
    'Bootstrap',1000, ...
    'RunTiming',true, ...
    'TimingNExponents',[], ... % Empty: largest N; specify a subset for a TAE curve
    'TimingReplications',20, ...
    'TimingWarmupExponent',12, ...
    'UseParallel',true, ...
    'NumWorkers',4, ...
    'OutputDir',fullfile(root,'results','gaussian'));
