% Standard product Gaussian: IID-MWG versus coordinatewise Array-RQMC-MWG.
% Edit all experiment settings here. One sweep updates coordinates 1:p.
%
% Entry script for coordinatewise Gaussian MWG. T and BurnIn count full sweeps.
% Array updates use a fresh scramble and the active coordinate's substream.
% Each N uses one combined parfor; checkpoint once per completed N.
% Default starts a new run; use an explicit checkpoint path to resume.

%% Resolve repository paths
driver=mfilename('fullpath');
assert(~isempty(driver),'Add the clean experiment folder to the MATLAB path first');
root=fileparts(driver); addpath(genpath(fullfile(root,'src')));

%% Configure and run the coordinatewise experiment
results=run_gaussian_mwg_experiment( ...
    'Dimensions',[2 4 8], ...
    'NExponents',10:18, ...
    'Replications',200, ...
    'T',128, ...             % Total full sweeps, INCLUDING BurnIn
    'BurnIn',8, ...          % Average sweeps 9:128, i.e. 120 observations
    'StepScale',2.38, ...    % One-dimensional proposal SD, same for every p
    'Initialization','zero', ... % 'zero', 'fixed', or 'stationary'
    'InitialState',[], ...   % For 'fixed': scalar, or row vector for a single p
    'Seed',2026, ...
    'TailCount',5, ...
    'Bootstrap',1000, ...    % 0 skips bootstrap confidence intervals
    'RunTiming',true, ...
    'TimingNExponents',[], ... % Empty: largest N; specify a subset for a TAE curve
    'TimingReplications',20, ...
    'TimingWarmupExponent',12, ...
    'UseParallel',true, ...
    'NumWorkers',4, ...
    'ValidateStratification',false, ... % Optional extra check at each update
    'OutputDir',fullfile(root,'results','gaussian_mwg'), ...
    'ResumePath','');    % 'auto': latest checkpoint; settings must match
                            % '': NEW run; full checkpoint path: explicit resume
