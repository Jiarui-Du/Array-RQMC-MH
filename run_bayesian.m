% Bayesian fixed-horizon experiment. Select all or one dataset and edit parameters here.
%
% Shared entry for Ripley and Pima logistic models with the existing flat prior.
% T includes BurnIn; retained estimates average transitions BurnIn+1:T.
% An explicit v3 checkpoint requires matching settings; empty ResumePath starts anew.

%% Select dataset
dataset='all'; % 'all', 'ripley' or 'pima'

%% Resolve repository paths
driver=mfilename('fullpath');
assert(~isempty(driver),'Run this script from the Array-RQMC-MH repository');
root=fileparts(driver); addpath(genpath(fullfile(root,'src')));
% BurnIn is the observation-window start, not a claim of stationarity.
% ResumePath: exact v3 checkpoint MAT path; match its simulation/timing settings.

%% Configure and run each selected dataset
if strcmp(dataset,'all'),datasets={'ripley','pima'};else,datasets={dataset};end
suiteTimer=tic;resultsByDataset=struct;
for datasetIndex=1:numel(datasets)
    dataset=datasets{datasetIndex};
    fprintf('\n[%d/%d] dataset=%s\n',datasetIndex,numel(datasets),dataset);
    results=run_bayesian_single_parfor( ...
        'Dataset',dataset, ...
        'NExponents',10:18, ...
        'Replications',200, ...
        'T',128, ...
        'BurnIn',8, ...
        'HilbertBits',[], ... % Auto: min(20,floor(64/p)); Ripley p=3: B=20; Pima p=8: B=8
        'PrecisionCheck',false, ...
        'CollisionCheck',false, ...
        'Seed',2026, ...
        'TailCount',5, ...
        'Bootstrap',1000, ...
        'StatisticalTestFunction','projection', ... % Statistics: projection only
        'TimingTestFunction','projection', ... % Independent serial timing of the projection test
        'RunTiming',true, ...
        'TimingNExponents',[], ... % Empty: largest N; specify a subset for a TAE curve
        'TimingReplications',20, ...
        'TimingWarmupExponent',12, ...
        'UseParallel',true, ...
        'NumWorkers',4, ...
        'OutputDir',fullfile(root,'runs','bayesian'), ...
        'ResumePath','');

    resultsByDataset.(dataset)=results;
end
fprintf('Total elapsed time (Bayesian suite): %.2f s\n',toc(suiteTimer));
