function artifacts = save_array_rqmc_chain_length_results(results)
%SAVE_ARRAY_RQMC_CHAIN_LENGTH_RESULTS Save MAT and reusable CSV artifacts.

    requested_mat = fullfile(results.output_dir, ...
        [results.result_tag, '.mat']);
    mat_file = array_rqmc_unique_output_path(requested_mat);
    [folder, stem] = fileparts(mat_file);
    base = fullfile(folder, stem);

    replication = (1:results.R).';
    T_names = arrayfun(@(T) sprintf('T%d', T), results.T_vec, ...
        'UniformOutput', false);
    raw_iid_table = addvars(array2table(results.est_mcmc_all, ...
        'VariableNames', T_names), replication, 'Before', 1, ...
        'NewVariableNames', 'Replication');
    raw_array_table = addvars(array2table(results.est_sobol_all, ...
        'VariableNames', T_names), replication, 'Before', 1, ...
        'NewVariableNames', 'Replication');
    acc_iid_table = addvars(array2table(results.acc_mcmc_all, ...
        'VariableNames', T_names), replication, 'Before', 1, ...
        'NewVariableNames', 'Replication');
    acc_array_table = addvars(array2table(results.acc_sobol_all, ...
        'VariableNames', T_names), replication, 'Before', 1, ...
        'NewVariableNames', 'Replication');

    results.raw_iid_table = raw_iid_table;
    results.raw_array_table = raw_array_table;
    results.acc_iid_table = acc_iid_table;
    results.acc_array_table = acc_array_table;
    save(mat_file, 'results', '-v7.3');

    artifacts = struct( ...
        'mat', mat_file, ...
        'summary_csv', [base, '_summary.csv'], ...
        'raw_iid_csv', [base, '_raw_IID.csv'], ...
        'raw_array_csv', [base, '_raw_Array.csv'], ...
        'acceptance_iid_csv', [base, '_acceptance_IID.csv'], ...
        'acceptance_array_csv', [base, '_acceptance_Array.csv'], ...
        'figure_stem', fullfile(folder, stem));
    writetable(results.summary_table, artifacts.summary_csv);
    writetable(raw_iid_table, artifacts.raw_iid_csv);
    writetable(raw_array_table, artifacts.raw_array_csv);
    writetable(acc_iid_table, artifacts.acceptance_iid_csv);
    writetable(acc_array_table, artifacts.acceptance_array_csv);

    array_rqmc_checkpoint('delete', results.checkpoint_file, []);
end
