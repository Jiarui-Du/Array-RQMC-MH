function catalog = array_rqmc_case_catalog()
%ARRAY_RQMC_CASE_CATALOG Paper targets and test functions.
%
% CATALOG.targets contains the four target distributions reported in the
% manuscript.  CATALOG.tests contains the three manuscript test functions:
%
%   f_CDF(x) = 1{x <= a_pi},   f(x) = x,   f(x) = x^2,
%
% where a_pi is the lower quartile of the corresponding target law.
%
% The lower quartiles below were computed once to high numerical accuracy
% from the normalized one-dimensional target densities.  They are used only
% to define the CDF test function and do not enter the Metropolis ratio.
%
% Target/test IDs are stable keys shared by simulation, filenames and plotting.
% The catalog stores handles and descriptive metadata; it does not run a chain.


    %% Define the four target log densities and CDF thresholds
    targets = repmat(empty_target(), 0, 1);

    targets(end+1) = make_target( ...
        'normal', ...
        'Standard normal', ...
        'Standard normal', ...
        @(x) -0.5 .* x.^2, ...
        true, ...
        0, ...
        -0.6744897501960817, ... % norminv(0.25)
        ['Standard normal target.  The CDF test threshold is its lower ', ...
         'quartile.']);

    targets(end+1) = make_target( ...
        'double_well_e1', ...
        'Double well', ...
        'Double well', ...
        @(x) -(x.^2 - 1).^2, ...
        true, ...
        0, ...
        -0.8671185496419450, ... % compute_target_quantile(@(x) -(x.^2 - 1).^2,0.25,[-5, 0]);
        ['Symmetric double-well target proportional to ', ...
         'exp(-(x^2-1)^2).']);

    targets(end+1) = make_target( ...
        'gaussian_mixture3', ...
        'Gaussian mixture', ...
        'Gaussian mixture', ...
        @log_pi_gaussian_mixture3, ...
        false, ...
        0, ...
        -1.4758426711005348, ... % compute_target_quantile(@log_pi_gaussian_mixture3,0.25,[-5, 0]);
        ['Asymmetric three-component Gaussian mixture.  The log density ', ...
         'is evaluated with a stable log-sum-exp formula.']);

    targets(end+1) = make_target( ...
        'student_t3', ...
        'Student t target with 3 degrees of freedom', ...
        'Student-$t_3$', ...
        @(x) -2 .* log1p(x.^2 ./ 3), ...
        true, ...
        0, ...
        -0.7648923284043444, ... % tinv(0.25, 3);
        ['Student-t target with three degrees of freedom.  The fourth ', ...
         'stationary moment is infinite.']);


    %% Define the three test functions and their metadata
    tests = repmat(empty_test(), 0, 1);

    tests(end+1) = make_test( ...
        'cdf', ...
        'f_CDF(x)=1{x<=a_pi}', ...
        'cdf_indicator', ...
        [], ...
        false, ...
        true, ...
        ['Target-dependent CDF indicator.  For each target, a_pi is the ', ...
         'lower quartile and V_R(f_CDF)=1.']);

    tests(end+1) = make_test( ...
        'x', ...
        'f(x)=x', ...
        'fixed_handle', ...
        @(x) x, ...
        true, ...
        false, ...
        ['Odd first-moment test.  It is unbounded and does not have finite ', ...
         'total variation on R.']);

    tests(end+1) = make_test( ...
        'x2', ...
        'f(x)=x^2', ...
        'fixed_handle', ...
        @(x) x.^2, ...
        false, ...
        false, ...
        ['Second-moment stress test.  It is unbounded and does not have ', ...
         'finite total variation on R.']);


    %% Assemble the catalog consumed by the suite
    catalog = struct;
    catalog.targets = targets;
    catalog.tests = tests;
    catalog.cdf_probability = 0.25;
end


%% Local helper: empty_target
% Define the common target metadata schema before appending catalog entries.
function s = empty_target()
    s = struct( ...
        'id', '', ...
        'label', '', ...
        'latex_label', '', ...
        'log_pi', [], ...
        'is_symmetric', false, ...
        'default_initial_state', 0, ...
        'cdf_probability', 0.25, ...
        'cdf_threshold', NaN, ...
        'note', '');
end


%% Local helper: make_target
% Populate one target entry without changing its log-density handle.
function s = make_target( ...
        id, label, latex_label, log_pi, is_symmetric, x0, ...
        cdf_threshold, note)

    s = empty_target();
    s.id = id;
    s.label = label;
    s.latex_label = latex_label;
    s.log_pi = log_pi;
    s.is_symmetric = logical(is_symmetric);
    s.default_initial_state = x0;
    s.cdf_probability = 0.25;
    s.cdf_threshold = double(cdf_threshold);
    s.note = note;
end


%% Local helper: empty_test
% Define the common test metadata schema before appending catalog entries.
function s = empty_test()
    s = struct( ...
        'id', '', ...
        'label', '', ...
        'kind', '', ...
        'handle', [], ...
        'is_odd', false, ...
        'finite_total_variation_on_R', false, ...
        'note', '');
end


%% Local helper: make_test
% Populate one test entry with its handle and descriptive flags.
function s = make_test(id, label, kind, handle, is_odd, is_bv, note)
    s = empty_test();
    s.id = id;
    s.label = label;
    s.kind = kind;
    s.handle = handle;
    s.is_odd = logical(is_odd);
    s.finite_total_variation_on_R = logical(is_bv);
    s.note = note;
end


%% Local helper: log_pi_gaussian_mixture3
% Use row-wise log-sum-exp and restore the input array shape.
function y = log_pi_gaussian_mixture3(x)
%LOG_PI_GAUSSIAN_MIXTURE3 Stable evaluation of
%
% exp(-2(x+1.5)^2) + 0.8 exp(-3x^2) + 0.6 exp(-4(x-1.5)^2).

    original_size = size(x);
    xv = double(x(:));

    terms = [ ...
        -2 .* (xv + 1.5).^2, ...
        log(0.8) - 3 .* xv.^2, ...
        log(0.6) - 4 .* (xv - 1.5).^2];

    row_max = max(terms, [], 2);
    yv = row_max + log(sum(exp(terms - row_max), 2));
    y = reshape(yv, original_size);
end
