function results = run_array_rqmc_statistical_experiment(varargin)
%RUN_ARRAY_RQMC_STATISTICAL_EXPERIMENT Joint IID/Array-RQMC experiment.
%
% For each N and replication, every selected test function is accumulated
% along one IID trajectory and one Array-RQMC trajectory. Timing is not
% performed here.
%
% Raw estimate arrays have axes replication, particle count and test.
% Compatible checkpoints resume after a fully completed particle count;
% random stream assignment is unchanged between serial and parallel execution.


    %% Validate inputs and construct kernels and execution settings
    opt = parse_options(varargin{:});
    if opt.T0 >= opt.T
        error('array_rqmc:TimeIndices', 'Require 0 <= T0 < T.');
    end
    [test_functions, test_ids, test_labels, reference_values] = ...
        array_rqmc_normalize_statistical_tests(opt);

    m_vec = sort(unique(reshape(double(opt.mVec), 1, [])));
    N_vec = 2 .^ m_vec;
    T0 = double(opt.T0);
    T = double(opt.T);
    R = double(opt.R);
    sigma = double(opt.sigma);
    x0 = double(opt.InitialState);
    log_pi = opt.LogPi;
    logp0 = array_rqmc_validate_handles(log_pi, test_functions, x0);
    use_parallel = array_rqmc_initialize_parallel( ...
        opt.UseParallel, opt.AutoStartPool);
    sobol_base = array_rqmc_sobol_base();


    %% Allocate raw estimates and load a compatible checkpoint
    test_count = numel(test_functions);
    N_count = numel(N_vec);
    data = struct( ...
        'est_mcmc', nan(R, N_count, test_count), ...
        'est_sobol', nan(R, N_count, test_count), ...
        'accept_mcmc', nan(R, N_count), ...
        'accept_sobol', nan(R, N_count));
    signature = checkpoint_signature(opt, m_vec, T0, T, R, sigma, x0, ...
        log_pi, test_functions, test_ids);
    completed_N_index = 0;
    checkpoint_file = char(opt.CheckpointFile);
    if opt.ResumeFromCheckpoint && ~isempty(checkpoint_file)
        checkpoint = array_rqmc_checkpoint( ...
            'load', checkpoint_file, []);
        if is_compatible_checkpoint(checkpoint, signature)
            data = checkpoint.data;
            completed_N_index = checkpoint.completed_N_index;
            fprintf('Resuming after N index %d.\n', completed_N_index);
        end
    end

    fprintf('============================================================\n');
    fprintf('Joint IID / Array-RQMC statistical experiment\n');
    fprintf('Tests: %s\n', strjoin(test_ids, ', '));
    fprintf('m values: %s; T0=%d; T=%d; R=%d; sigma=%.6g; x0=%.6g\n', ...
        mat2str(m_vec), T0, T, R, sigma, x0);
    fprintf('Parallel execution: %d\n', use_parallel);
    fprintf('============================================================\n');


    statsTimer=tic;
    %% Run independent macro replications over the remaining grid
    for N_index = completed_N_index + 1:N_count
        N = N_vec(N_index);
        m = m_vec(N_index);
        estimates_iid = nan(R, test_count);
        estimates_array = nan(R, test_count);
        acceptance_iid = nan(R, 1);
        acceptance_array = nan(R, 1);
        timer = tic;

        if use_parallel
            parfor replication = 1:R
                [estimates_iid(replication, :), ...
                 estimates_array(replication, :), ...
                 acceptance_iid(replication), ...
                 acceptance_array(replication)] = ...
                    array_rqmc_run_macro_replication( ...
                        N, m, T0, T, sigma, x0, logp0, log_pi, ...
                        test_functions, sobol_base, opt.MasterSeed, ...
                        replication);
            end
        else
            for replication = 1:R
                [estimates_iid(replication, :), ...
                 estimates_array(replication, :), ...
                 acceptance_iid(replication), ...
                 acceptance_array(replication)] = ...
                    array_rqmc_run_macro_replication( ...
                        N, m, T0, T, sigma, x0, logp0, log_pi, ...
                        test_functions, sobol_base, opt.MasterSeed, ...
                        replication);
            end
        end


        %% Store a completed grid point and checkpoint its state
        data.est_mcmc(:, N_index, :) = reshape( ...
            estimates_iid, R, 1, test_count);
        data.est_sobol(:, N_index, :) = reshape( ...
            estimates_array, R, 1, test_count);
        data.accept_mcmc(:, N_index) = acceptance_iid;
        data.accept_sobol(:, N_index) = acceptance_array;
        if ~isempty(checkpoint_file)
            checkpoint = struct('signature', signature, 'data', data, ...
                'completed_N_index', N_index, 'saved_at', datetime('now'));
            array_rqmc_checkpoint('save', checkpoint_file, checkpoint);
        end
        fprintf('N=2^%d completed in %.2f s\n',m,toc(timer));
    end


    fprintf('Statistical block total: %.2f s\n',toc(statsTimer));
    %% Attach provenance and compute empirical summaries
    settings = build_settings(opt, T0, T, R, sigma, x0, use_parallel, ...
        log_pi, test_functions, test_ids, test_labels, reference_values);
    results = summarize_array_rqmc_results( ...
        N_vec, m_vec, data, settings, reference_values, ...
        double(opt.SlopeTailCount));
end

%% Local helper: checkpoint_signature
% Record the grid, kernels and random-stream settings used to match checkpoints.
function signature = checkpoint_signature( ...
        opt, m_vec, T0, T, R, sigma, x0, log_pi, test_functions, test_ids)
    signature = struct('m_vec', m_vec, 'T0', T0, 'T', T, 'R', R, ...
        'sigma', sigma, 'x0', x0, 'master_seed', double(opt.MasterSeed), ...
        'substream_formula', ...
            'm * 1e9 + m * 1e6 + replication', ...
        'log_pi', func2str(log_pi), 'test_ids', {test_ids}, ...
        'test_functions', {cellfun(@func2str, test_functions, ...
            'UniformOutput', false)});
end

%% Local helper: is_compatible_checkpoint
% Accept only a checkpoint whose saved signature exactly matches this run.
function tf = is_compatible_checkpoint(checkpoint, signature)
    tf = isstruct(checkpoint) && isfield(checkpoint, 'signature') && ...
        isfield(checkpoint, 'data') && ...
        isfield(checkpoint, 'completed_N_index') && ...
        isequaln(checkpoint.signature, signature);
end

%% Local helper: build_settings
% Record resolved execution settings and the simulation/reproducibility conventions.
function settings = build_settings( ...
        opt, T0, T, R, sigma, x0, use_parallel, log_pi, ...
        test_functions, test_ids, test_labels, reference_values)
    settings = struct( ...
        'T0', T0, 'T', T, 'R', R, 'sigma', sigma, ...
        'initial_state', x0, 'reference_values', reference_values, ...
        'master_seed', double(opt.MasterSeed), ...
        'use_parallel_requested', opt.UseParallel, ...
        'use_parallel_actual', use_parallel, ...
        'auto_start_pool', opt.AutoStartPool, ...
        'checkpoint_file', char(opt.CheckpointFile), ...
        'resume_from_checkpoint', opt.ResumeFromCheckpoint, ...
        'slope_tail_count', double(opt.SlopeTailCount), ...
        'bootstrap_count', double(opt.Bootstrap), ...
        'log_pi', func2str(log_pi), ...
        'test_ids', {test_ids}, 'test_labels', {test_labels}, ...
        'test_functions', {cellfun(@func2str, test_functions, ...
            'UniformOutput', false)}, ...
        'number_of_test_functions', numel(test_functions), ...
        'statistical_simulation_scope', ...
            'All tests are accumulated jointly along one simulation.', ...
        'iid_proposal_generation', ...
            'Gaussian increments generated directly by RANDN.', ...
        'array_rqmc_point_set', ...
            'Three-dimensional Sobol sequence with PointOrder=graycode.', ...
        'array_rqmc_randomization', ...
            'Fresh MATLAB MatousekAffineOwen scrambling every transition.', ...
        'array_rqmc_matching', ...
            'Exact first-coordinate stratum rank matches sorted states.');
end

%% Local helper: parse_options
% Parse and validate the public name/value interface for this operation.
function opt = parse_options(varargin)
    ip = inputParser;
    ip.FunctionName = mfilename;
    addParameter(ip, 'mVec', 8:11, @valid_m_vector);
    addParameter(ip, 'T0', 8, @nonnegative_integer);
    addParameter(ip, 'T', 128, @positive_integer);
    addParameter(ip, 'R', 50, @replication_count);
    addParameter(ip, 'sigma', 2.38, @positive_scalar);
    addParameter(ip, 'LogPi', @(x) -0.5 .* x.^2, ...
        @(x) isa(x, 'function_handle'));
    addParameter(ip, 'TestFunctions', {}, @test_functions);
    addParameter(ip, 'TestFunction', [], ...
        @(x) isempty(x) || isa(x, 'function_handle'));
    addParameter(ip, 'TestFunctionIDs', {}, @text_list);
    addParameter(ip, 'TestFunctionLabels', {}, @text_list);
    addParameter(ip, 'InitialState', 0, @real_scalar);
    addParameter(ip, 'ReferenceValues', [], @reference_values);
    addParameter(ip, 'ReferenceValue', NaN, @reference_value);
    addParameter(ip, 'MasterSeed', 2026, @nonnegative_integer);
    addParameter(ip, 'UseParallel', true, @logical_scalar);
    addParameter(ip, 'AutoStartPool', true, @logical_scalar);
    addParameter(ip, 'Bootstrap', 1000, @nonnegative_integer);
    addParameter(ip, 'SlopeTailCount', 5, @(x) positive_integer(x) && x >= 2);
    addParameter(ip, 'CheckpointFile', '', @text_scalar);
    addParameter(ip, 'ResumeFromCheckpoint', true, @logical_scalar);
    parse(ip, varargin{:});
    opt = ip.Results;
end

%% Local input validators
% Predicates used by the option parser; they do not alter supplied values.
function tf = valid_m_vector(x), tf = isnumeric(x) && isvector(x) && ...
    ~isempty(x) && all(isfinite(x)) && all(x == floor(x)) && ...
    all(x >= 1) && all(x <= 30); end
function tf = nonnegative_integer(x), tf = isnumeric(x) && isscalar(x) && ...
    isfinite(x) && x == floor(x) && x >= 0; end
function tf = positive_integer(x), tf = nonnegative_integer(x) && x >= 1; end
function tf = replication_count(x), tf = positive_integer(x) && x >= 2; end
function tf = positive_scalar(x), tf = isnumeric(x) && isscalar(x) && ...
    isreal(x) && isfinite(x) && x > 0; end
function tf = real_scalar(x), tf = isnumeric(x) && isscalar(x) && ...
    isreal(x) && isfinite(x); end
function tf = logical_scalar(x), tf = islogical(x) && isscalar(x); end
function tf = text_scalar(x), tf = ischar(x) || ...
    (isstring(x) && isscalar(x)); end
function tf = test_functions(x), tf = isempty(x) || ...
    isa(x, 'function_handle') || (iscell(x) && ~isempty(x) && ...
    all(cellfun(@(h) isa(h, 'function_handle'), x(:)))); end
function tf = text_list(x), tf = isempty(x) || ischar(x) || ...
    isstring(x) || (iscell(x) && all(cellfun(@(v) ischar(v) || ...
    (isstring(v) && isscalar(v)), x(:)))); end
function tf = reference_values(x), tf = isempty(x) || ...
    (isnumeric(x) && isreal(x) && isvector(x) && ...
    all(isfinite(x) | isnan(x))); end
function tf = reference_value(x), tf = isnumeric(x) && isscalar(x) && ...
    isreal(x) && (isfinite(x) || isnan(x)); end
