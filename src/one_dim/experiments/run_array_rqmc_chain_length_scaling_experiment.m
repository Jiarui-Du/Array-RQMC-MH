function results = run_array_rqmc_chain_length_scaling_experiment(varargin)
%RUN_ARRAY_RQMC_CHAIN_LENGTH_SCALING_EXPERIMENT Compare chain scaling over N.
%
% The experiment reuses or computes one standard chain-length result per N.
% Its aggregate output contains Array-RQMC variance and
% N^(4/3)*variance versus effective length L=T-T0. The scaling comparison is
% an empirical diagnostic, not a theorem.

    totalTimer=tic;
    opt = parse_options(varargin{:});
    ensure_directory(opt.SingleNOutputDir);
    ensure_directory(opt.OutputDir);

    N_vec = double(opt.NVec(:).');
    m_vec = round(log2(N_vec));
    if any(N_vec ~= 2.^m_vec)
        error('array_rqmc:ParticlePowersOfTwo', ...
            'Every value in NVec must be an exact power of two.');
    end

    N_count = numel(N_vec);
    T_count = numel(opt.TVec);
    variance_iid = nan(T_count, N_count);
    variance_array = nan(T_count, N_count);
    slope_array = nan(N_count, 1);
    slope_standard_error = nan(N_count, 1);
    slope_r_squared = nan(N_count, 1);
    individual_result_files = cell(N_count, 1);
    individual_results = cell(N_count, 1);

    for N_index = 1:N_count
        N = N_vec(N_index);
        fprintf('\n[%d/%d] N=2^%d; target=%s; test=%s\n',N_index,N_count,m_vec(N_index),opt.TargetID,opt.TestFunctionID);
        single_tag = sprintf('%s_%s_N2p%d_T0_%d_R_%d', ...
            opt.TargetID, opt.TestFunctionID, m_vec(N_index), ...
            opt.T0, opt.R);
        expected_file = fullfile(opt.SingleNOutputDir, ...
            [single_tag, '.mat']);

        if opt.ReuseCompletedResults && isfile(expected_file)
            loaded = load(expected_file, 'results');
            if ~isfield(loaded, 'results') || ~isstruct(loaded.results)
                error('array_rqmc:InvalidChainResult', ...
                    'Missing results struct in %s.', expected_file);
            end
            single = loaded.results;
            validate_single_result(single, opt, N);
            individual_file = expected_file;
            fprintf('Reusing completed N=2^%d result: %s\n', ...
                m_vec(N_index), individual_file);
        else
            single = run_array_rqmc_chain_length_experiment( ...
                'TargetID', opt.TargetID, ...
                'TestFunctionID', opt.TestFunctionID, ...
                'N', N, 'T0', opt.T0, 'TVec', opt.TVec, ...
                'R', opt.R, 'sigma', opt.sigma, ...
                'InitialState', opt.InitialState, ...
                'MasterSeed', opt.MasterSeed, ...
                'UseParallel', opt.UseParallel, ...
                'AutoStartPool', opt.AutoStartPool, ...
                'OutputDir', opt.SingleNOutputDir, ...
                'ResumeFromCheckpoint', opt.ResumeFromCheckpoint, ...
                'ConfidenceLevel', opt.ConfidenceLevel);
            artifacts = save_array_rqmc_chain_length_results(single);
            individual_file = artifacts.mat;
            fprintf('Saved completed N=2^%d result: %s\n', ...
                m_vec(N_index), individual_file);
        end

        fit = array_rqmc_fit_loglog_slope( ...
            single.effective_T, single.var_sobol, opt.SlopeTailCount);
        variance_iid(:, N_index) = double(single.var_mcmc(:));
        variance_array(:, N_index) = double(single.var_sobol(:));
        slope_array(N_index) = fit.slope;
        slope_standard_error(N_index) = fit.standard_error;
        slope_r_squared(N_index) = fit.r_squared;
        individual_result_files{N_index} = individual_file;
        individual_results{N_index} = single;
    end

    scaling_exponent = 4 / 3;
    scaled_variance_array = variance_array .* ...
        reshape(N_vec.^scaling_exponent, 1, []);
    effective_T = double(opt.TVec(:)) - double(opt.T0);
    [result_file, result_tag] = array_rqmc_chain_scaling_filename( ...
        opt.OutputDir, opt.TargetID, opt.TestFunctionID, N_vec, ...
        opt.T0, opt.TVec, opt.R, opt.sigma, opt.InitialState, ...
        opt.MasterSeed);

    first = individual_results{1};
    results = struct( ...
        'target_id', opt.TargetID, ...
        'target_label', first.target_label, ...
        'test_id', opt.TestFunctionID, ...
        'test_label', first.test_label, ...
        'N_vec', N_vec(:), ...
        'm_vec', m_vec(:), ...
        'T0', double(opt.T0), ...
        'T_vec', double(opt.TVec(:)), ...
        'effective_T', effective_T, ...
        'R', double(opt.R), ...
        'sigma', double(opt.sigma), ...
        'x0', double(opt.InitialState), ...
        'master_seed', double(opt.MasterSeed), ...
        'variance_iid', variance_iid, ...
        'variance_array', variance_array, ...
        'scaling_exponent', scaling_exponent, ...
        'scaled_variance_array', scaled_variance_array, ...
        'slope_array', slope_array, ...
        'slope_standard_error', slope_standard_error, ...
        'slope_r_squared', slope_r_squared, ...
        'individual_result_files', {individual_result_files}, ...
        'output_dir', opt.OutputDir, ...
        'result_file', result_file, ...
        'result_tag', result_tag, ...
        'empirical_claim', [ ...
            'Diagnostic only: variance approximately N^(-4/3)L^(-1); ', ...
            'not a theorem.'], ...
        'saved_at', datetime('now'), ...
        'matlab_version', version, ...
        'computer', computer);
    results.individual_results=individual_results;
    results.total_elapsed_sec=toc(totalTimer);
    fprintf('Total elapsed time: %.2f s\n',results.total_elapsed_sec);
    results.summary_table = make_summary_table(results);
    results.slope_table = table(results.N_vec, results.m_vec, ...
        slope_array, slope_standard_error, slope_r_squared, ...
        'VariableNames', {'N','m','ArraySlope','SlopeSE','RSquared'});
    results.reproducibility = struct( ...
        'schema_version', 2, ...
        'stream_type', 'mrg32k3a', ...
        'method_offsets', [11, 37], ...
        'substream_formula', ...
            'm * 1e9 + T index * 1e6 + replication', ...
        'reuse_completed_results', opt.ReuseCompletedResults);
end

function summary = make_summary_table(results)
    N_count = numel(results.N_vec);
    T_count = numel(results.T_vec);
    N = repelem(results.N_vec, T_count);
    m = repelem(results.m_vec, T_count);
    T = repmat(results.T_vec, N_count, 1);
    EffectiveLength = repmat(results.effective_T, N_count, 1);
    Var_IID = results.variance_iid(:);
    Var_Array = results.variance_array(:);
    ScaledVar_Array = results.scaled_variance_array(:);
    ArraySlope = repelem(results.slope_array, T_count);
    summary = table(N, m, T, EffectiveLength, Var_IID, Var_Array, ...
        ScaledVar_Array, ArraySlope);
end

function validate_single_result(single, opt, N)
    required = {'target_id','test_id','N','T0','T_vec','R','sigma', ...
        'x0','master_seed','effective_T','var_mcmc','var_sobol', ...
        'reproducibility'};
    if ~all(isfield(single, required))
        error('array_rqmc:InvalidChainResult', ...
            'A reusable single-N result is missing required fields.');
    end
    compatible = strcmp(single.target_id, opt.TargetID) && ...
        strcmp(single.test_id, opt.TestFunctionID) && ...
        double(single.N) == double(N) && ...
        double(single.T0) == double(opt.T0) && ...
        isequal(double(single.T_vec(:).'), double(opt.TVec)) && ...
        double(single.R) == double(opt.R) && ...
        double(single.sigma) == double(opt.sigma) && ...
        double(single.x0) == double(opt.InitialState) && ...
        double(single.master_seed) == double(opt.MasterSeed) && ...
        isfield(single.reproducibility, 'substream_formula') && ...
        strcmp(single.reproducibility.substream_formula, ...
            'm * 1e9 + T index * 1e6 + replication');
    if ~compatible
        error('array_rqmc:IncompatibleChainResult', ...
            'Existing single-N result does not match the requested settings.');
    end
end

function ensure_directory(folder)
    if ~isfolder(folder)
        [ok, message] = mkdir(folder);
        if ~ok
            error('array_rqmc:CreateDirectory', ...
                'Could not create %s: %s', folder, message);
        end
    end
end

function opt = parse_options(varargin)
    ip = inputParser;
    ip.FunctionName = 'run_array_rqmc_chain_length_scaling_experiment';
    addParameter(ip, 'TargetID', 'gaussian_mixture3', @text_scalar);
    addParameter(ip, 'TestFunctionID', 'cdf', @text_scalar);
    addParameter(ip, 'NVec', 2.^[12,14,16], @integer_vector);
    addParameter(ip, 'T0', 2^7, @nonnegative_integer);
    addParameter(ip, 'TVec', 2.^(8:16), @integer_vector);
    addParameter(ip, 'R', 50, @replication_count);
    addParameter(ip, 'sigma', 2.38, @positive_scalar);
    addParameter(ip, 'InitialState', 0, @real_scalar);
    addParameter(ip, 'MasterSeed', 2026, @nonnegative_integer);
    addParameter(ip, 'UseParallel', true, @logical_scalar);
    addParameter(ip, 'AutoStartPool', true, @logical_scalar);
    addParameter(ip, 'SingleNOutputDir', ...
        fullfile(pwd, 'results', 'one_dim_horizon', 'individual'), @text_scalar);
    addParameter(ip, 'OutputDir', ...
        fullfile(pwd, 'results', 'one_dim_horizon'), @text_scalar);
    addParameter(ip, 'ResumeFromCheckpoint', true, @logical_scalar);
    addParameter(ip, 'ReuseCompletedResults', true, @logical_scalar);
    addParameter(ip, 'SlopeTailCount', 5, ...
        @(x) positive_integer(x) && x >= 2);
    addParameter(ip, 'ConfidenceLevel', 0.95, ...
        @(x) isnumeric(x) && isscalar(x) && isfinite(x) && x > 0 && x < 1);
    parse(ip, varargin{:});
    opt = ip.Results;
    opt.TargetID = char(opt.TargetID);
    opt.TestFunctionID = char(opt.TestFunctionID);
    opt.SingleNOutputDir = char(opt.SingleNOutputDir);
    opt.OutputDir = char(opt.OutputDir);
    opt.NVec = reshape(double(opt.NVec), 1, []);
    opt.TVec = reshape(double(opt.TVec), 1, []);
    if any(opt.TVec <= opt.T0)
        error('array_rqmc:TimeIndices', ...
            'Every chain length must satisfy T > T0.');
    end
end

function tf = text_scalar(x), tf = ischar(x) || ...
    (isstring(x) && isscalar(x)); end
function tf = nonnegative_integer(x), tf = isnumeric(x) && isscalar(x) && ...
    isfinite(x) && x == floor(x) && x >= 0; end
function tf = positive_integer(x), tf = nonnegative_integer(x) && x >= 1; end
function tf = integer_vector(x), tf = isnumeric(x) && isvector(x) && ...
    ~isempty(x) && all(isfinite(x)) && all(x == floor(x)) && all(x >= 1); end
function tf = replication_count(x), tf = positive_integer(x) && x >= 2; end
function tf = positive_scalar(x), tf = isnumeric(x) && isreal(x) && ...
    isscalar(x) && isfinite(x) && x > 0; end
function tf = real_scalar(x), tf = isnumeric(x) && isreal(x) && ...
    isscalar(x) && isfinite(x); end
function tf = logical_scalar(x), tf = islogical(x) && isscalar(x); end
