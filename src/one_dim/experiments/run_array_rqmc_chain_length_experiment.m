function results = run_array_rqmc_chain_length_experiment(varargin)
%RUN_ARRAY_RQMC_CHAIN_LENGTH_EXPERIMENT Simulate a fixed-N chain-length grid.

    totalTimer=tic;
    %% Resolve the target, tests and checkpoint
    opt = array_rqmc_parse_chain_options(varargin{:});
    if ~isfolder(opt.OutputDir)
        [ok, message] = mkdir(opt.OutputDir);
        if ~ok
            error('array_rqmc:CreateDirectory', ...
                'Could not create %s: %s', opt.OutputDir, message);
        end
    end
    catalog = array_rqmc_case_catalog();
    target = array_rqmc_select_catalog_entries( ...
        catalog.targets, opt.TargetID, 'target');
    test = array_rqmc_select_catalog_entries( ...
        catalog.tests, opt.TestFunctionID, 'test function');
    [test_functions, ~, test_labels] = ...
        array_rqmc_resolve_tests(test, target, double(opt.InitialState));

    tag = sprintf('%s_%s_N2p%d_T0_%d_R_%d', target.id, test.id, ...
        round(log2(double(opt.N))), opt.T0, opt.R);
    checkpoint_file = fullfile(opt.OutputDir, [tag, '_checkpoint.mat']);
    raw = initialize_raw(opt.R, numel(opt.TVec));
    if opt.ResumeFromCheckpoint
        checkpoint = array_rqmc_checkpoint( ...
            'load', checkpoint_file, []);
        [raw, checkpoint_format] = restore_checkpoint( ...
            checkpoint, opt, target.id, test.id, raw);
        if ~isempty(checkpoint) && isempty(checkpoint_format)
            error('array_rqmc:IncompatibleCheckpoint','Checkpoint settings do not match this run.');
        end
        if ~isempty(checkpoint_format)
            fprintf('Resuming %s checkpoint after T index %d.\n', ...
                checkpoint_format, raw.completed_idx);
        end
    end

    use_parallel = logical(opt.UseParallel);
    if raw.completed_idx < numel(opt.TVec)
        log_pi = target.log_pi;
        logp0 = array_rqmc_validate_handles( ...
            log_pi, test_functions, double(opt.InitialState));
        sobol_base = array_rqmc_sobol_base();
        use_parallel = array_rqmc_initialize_parallel( ...
            opt.UseParallel, opt.AutoStartPool);
    end

    fprintf('============================================================\n');
    fprintf('Chain-length experiment: target=%s, test=%s\n', ...
        target.id, test.id);
    fprintf('N=%d; T0=%d; T=%s; R=%d; parallel=%d\n', ...
        opt.N, opt.T0, mat2str(opt.TVec), opt.R, use_parallel);
    fprintf('============================================================\n');

    for T_index = raw.completed_idx + 1:numel(opt.TVec)
        T = opt.TVec(T_index);
        timer = tic;
        estimates_iid = nan(opt.R, 1);
        estimates_array = nan(opt.R, 1);
        acceptance_iid = nan(opt.R, 1);
        acceptance_array = nan(opt.R, 1);
        if use_parallel
            parfor replication = 1:opt.R
                [estimates_iid(replication), estimates_array(replication), ...
                 acceptance_iid(replication), acceptance_array(replication)] = ...
                    array_rqmc_run_macro_replication( ...
                        opt.N, T_index, opt.T0, T, opt.sigma, ...
                        opt.InitialState, logp0, log_pi, test_functions, ...
                        sobol_base, opt.MasterSeed, replication);
            end
        else
            for replication = 1:opt.R
                [estimates_iid(replication), estimates_array(replication), ...
                 acceptance_iid(replication), acceptance_array(replication)] = ...
                    array_rqmc_run_macro_replication( ...
                        opt.N, T_index, opt.T0, T, opt.sigma, ...
                        opt.InitialState, logp0, log_pi, test_functions, ...
                        sobol_base, opt.MasterSeed, replication);
            end
        end
        raw.est_mcmc_all(:, T_index) = estimates_iid;
        raw.est_sobol_all(:, T_index) = estimates_array;
        raw.acc_mcmc_all(:, T_index) = acceptance_iid;
        raw.acc_sobol_all(:, T_index) = acceptance_array;
        raw.elapsed_sec(T_index) = toc(timer);
        raw.completed_idx = T_index;
        payload = struct('target_id', target.id, 'test_id', test.id, ...
            'settings', checkpoint_settings(opt), 'raw', raw, ...
            'saved_at', datetime('now'));
        array_rqmc_checkpoint('save', checkpoint_file, payload);
        fprintf('T=%d (L=%d) completed in %.2f s\n', T, T-opt.T0, raw.elapsed_sec(T_index));
    end

    context = struct('target_id', target.id, ...
        'target_label', target.label, 'test_id', test.id, ...
        'test_label', test_labels{1}, 'N', double(opt.N), ...
        'T0', double(opt.T0), 'T_vec', double(opt.TVec), ...
        'R', double(opt.R), 'sigma', double(opt.sigma), ...
        'x0', double(opt.InitialState), ...
        'master_seed', double(opt.MasterSeed), ...
        'use_parallel', use_parallel, 'output_dir', opt.OutputDir, ...
        'result_tag', tag, 'checkpoint_file', checkpoint_file, ...
        'confidence_level', opt.ConfidenceLevel, ...
        'stationary_reference', ...
            array_rqmc_stationary_reference(target, test.id));
    if strcmp(test.id, 'cdf')
        context.cdf_threshold = target.cdf_threshold;
        context.cdf_probability = target.cdf_probability;
    end
    results = summarize_array_rqmc_chain_length(raw, context);
    results.total_elapsed_sec=toc(totalTimer);
    fprintf('N=2^%d completed in %.2f s\n',round(log2(opt.N)),results.total_elapsed_sec);
end

function raw = initialize_raw(R, count)
    raw = struct('est_mcmc_all', nan(R, count), ...
        'est_sobol_all', nan(R, count), ...
        'acc_mcmc_all', nan(R, count), ...
        'acc_sobol_all', nan(R, count), ...
        'elapsed_sec', nan(count, 1), 'completed_idx', 0);
end

function settings = checkpoint_settings(opt)
    settings = struct('N', double(opt.N), 'T0', double(opt.T0), ...
        'T_vec', double(opt.TVec), 'R', double(opt.R), ...
        'sigma', double(opt.sigma), 'x0', double(opt.InitialState), ...
        'master_seed', double(opt.MasterSeed), ...
        'substream_formula', ...
            'm * 1e9 + T index * 1e6 + replication');
end

function [raw, format] = restore_checkpoint( ...
        checkpoint, opt, target_id, test_id, default_raw)
    raw = default_raw;
    format = '';
    if is_compatible_checkpoint(checkpoint, opt, target_id, test_id)
        raw = checkpoint.raw;
        format = 'current';
    elseif is_compatible_legacy_checkpoint( ...
            checkpoint, opt, target_id, test_id)
        raw.est_mcmc_all = double(checkpoint.est_mcmc_all);
        raw.est_sobol_all = double(checkpoint.est_sobol_all);
        raw.acc_mcmc_all = double(checkpoint.acc_mcmc_all);
        raw.acc_sobol_all = double(checkpoint.acc_sobol_all);
        raw.elapsed_sec = double(checkpoint.elapsed_sec(:));
        raw.completed_idx = double(checkpoint.completed_idx);
        format = 'legacy';
    end
end

function tf = is_compatible_checkpoint(checkpoint, opt, target_id, test_id)
    tf = isstruct(checkpoint) && isfield(checkpoint, 'raw') && ...
        isfield(checkpoint, 'settings') && ...
        strcmp(checkpoint.target_id, target_id) && ...
        strcmp(checkpoint.test_id, test_id) && ...
        isequaln(checkpoint.settings, checkpoint_settings(opt));
end

function tf = is_compatible_legacy_checkpoint( ...
        checkpoint, opt, target_id, test_id)
    required_fields = {'target_id','test_id','N','T0','T_vec','R', ...
        'sigma','x0','master_seed','completed_idx','est_mcmc_all', ...
        'est_sobol_all','acc_mcmc_all','acc_sobol_all','elapsed_sec'};
    tf = isstruct(checkpoint) && all(isfield(checkpoint, required_fields));
    if ~tf
        return;
    end

    legacy_settings = struct('N', double(checkpoint.N), ...
        'T0', double(checkpoint.T0), ...
        'T_vec', double(checkpoint.T_vec), ...
        'R', double(checkpoint.R), ...
        'sigma', double(checkpoint.sigma), ...
        'x0', double(checkpoint.x0), ...
        'master_seed', double(checkpoint.master_seed));
    expected_size = [double(opt.R), numel(opt.TVec)];
    raw_fields = {'est_mcmc_all','est_sobol_all', ...
        'acc_mcmc_all','acc_sobol_all'};
    sizes_match = all(cellfun(@(name) ...
        isequal(size(checkpoint.(name)), expected_size), raw_fields));
    completed_idx = double(checkpoint.completed_idx);
    tf = strcmp(checkpoint.target_id, target_id) && ...
        strcmp(checkpoint.test_id, test_id) && ...
        isequaln(legacy_settings, checkpoint_settings(opt)) && ...
        sizes_match && isscalar(completed_idx) && ...
        isfinite(completed_idx) && completed_idx >= 0 && ...
        completed_idx <= numel(opt.TVec);
end
